#!/usr/bin/env node
// Writes the pg-boss schema as a Prisma migration, so the queue schema is versioned and applied
// by `prisma migrate` (as the schema owner) and the API runs pg-boss with migrate: false.
// Usage: node scripts/pgboss-migration.mjs            -> construction plan (new database)
//        node scripts/pgboss-migration.mjs <from-ver>  -> upgrade plan after bumping pg-boss
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getConstructionPlans, getMigrationPlans } from 'pg-boss';

const SCHEMA = 'pgboss';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = createRequire(import.meta.url)('pg-boss/package.json');

const fromVersion = process.argv[2];
const sql = fromVersion
  ? getMigrationPlans(SCHEMA, Number(fromVersion))
  : getConstructionPlans(SCHEMA);

const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const name = `${stamp}_pgboss_${version.replaceAll('.', '_')}`;
const dir = join(root, 'prisma', 'migrations', name);
mkdirSync(dir, { recursive: true });
writeFileSync(
  join(dir, 'migration.sql'),
  `-- Generated by scripts/pgboss-migration.mjs from pg-boss ${version}. Do not edit by hand.\n${sql}\n`,
);
console.log(`Wrote ${join('prisma', 'migrations', name, 'migration.sql')}`);
